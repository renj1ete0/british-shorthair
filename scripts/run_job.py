#!/usr/bin/env python3
"""Single entry point for every collection job.

    python run_job.py --list                       show all jobs and schedules
    python run_job.py --crontab                    print the generated crontab
    python run_job.py bus_arrival                  run one job
    python run_job.py mss --date 2026-08-01        run for a specific date
    python run_job.py mss_backfill --days 120      on-demand backfill
    python run_job.py --announce                   send the startup notice (entrypoint)

The crontab supercronic runs is generated from the job registry, so a job's schedule
is declared next to its code and the two cannot drift apart.
"""

import argparse
import inspect
import sys

from bsh import jobs  # noqa: F401  (registers all jobs)
from bsh.registry import all_jobs, get, scheduled_jobs, to_cron
from bsh.runner import run

CRON_COMMAND = "cd /app/scripts && python run_job.py {name}"


def build_crontab():
    lines = [
        "# Generated by run_job.py --crontab - do not edit by hand.",
        "# Schedules live on the @job decorator in bsh/jobs/*.py.",
        "# '@every N' schedules are translated to 6-field cron (leading seconds column)",
        "# because supercronic rejects the @every form.",
        "",
    ]
    for definition in scheduled_jobs():
        schedule = to_cron(definition.schedule)
        lines.append(f"# {definition.description}")
        if schedule != definition.schedule:
            lines.append(f"# declared as: {definition.schedule}")
        lines.append(f"{schedule} {CRON_COMMAND.format(name=definition.name)}")
        lines.append("")
    return "\n".join(lines)


def announce():
    """Log and send the startup notice naming the running version. Never fails boot."""
    import logging

    from bsh import __version__, notify

    logging.basicConfig(level=logging.INFO, format="%(message)s")
    logger = logging.getLogger("announce")
    try:
        notify.startup(__version__, logger=logger)
    except Exception as exc:  # noqa: BLE001 - a notice must never stop the collector
        logger.warning("startup notice failed: %s", exc)
    return 0


def list_jobs():
    width = max(len(j.name) for j in all_jobs())
    print(f"{'JOB'.ljust(width)}  {'SCHEDULE'.ljust(14)}  DESCRIPTION")
    for definition in all_jobs():
        schedule = definition.schedule or "on demand"
        print(f"{definition.name.ljust(width)}  {schedule.ljust(14)}  {definition.description}")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("job", nargs="?", help="name of the job to run")
    parser.add_argument("--list", action="store_true", help="list jobs and exit")
    parser.add_argument("--crontab", action="store_true", help="print the crontab and exit")
    parser.add_argument("--announce", action="store_true",
                        help="send the startup notice with the running version and exit")
    parser.add_argument("--date", help="target date, YYYY-MM-DD (mss, archive, daily_summary)")
    parser.add_argument("--month", help="target month, YYYYMM (datamall_pv)")
    parser.add_argument("--from", dest="start", help="backfill offset date, YYYY-MM-DD")
    parser.add_argument("--days", type=int, help="number of dates to backfill")
    args = parser.parse_args(argv)

    if args.list:
        list_jobs()
        return 0
    if args.crontab:
        print(build_crontab())
        return 0
    if args.announce:
        return announce()
    if not args.job:
        parser.print_help()
        return 2

    try:
        definition = get(args.job)
    except KeyError:
        print(f"unknown job: {args.job}\n", file=sys.stderr)
        list_jobs()
        return 2

    # Pass only the options this job's signature actually accepts, so one flat CLI
    # can serve jobs with different parameters.
    accepted = inspect.signature(definition.fn).parameters
    candidates = {"date": args.date, "month": args.month, "start": args.start, "days": args.days}
    kwargs = {k: v for k, v in candidates.items() if v is not None and k in accepted}

    if "date" in kwargs:
        from datetime import date as date_cls

        kwargs["date"] = date_cls.fromisoformat(kwargs["date"])

    return run(args.job, **kwargs)


if __name__ == "__main__":
    sys.exit(main())
